/**
 * 会话：设备的连接、画面通道与相关生命周期。
 *
 * 关键设计（参考 scrcpy 官方客户端的做法）：
 *   1. **视频帧走独立 MessagePort**，不占用主 IPC 队列。
 *      主 IPC 还要跑设置、音频、通知等，逐帧挤在一起会互相拖慢。
 *   2. **帧丢弃**：界面来不及消费时，只保留最新的关键帧 + 其后的帧，
 *      旧的非关键帧直接丢掉。宁可少几帧，也不要让队列无限堆积——
 *      堆积正是「越用越卡」的根源。
 *   3. 发送前把 Buffer 转成 Uint8Array：Node Buffer 无法结构化克隆，
 *      直接发会每帧报 An object could not be cloned。
 */
'use strict';

const { Scrcpy通道 } = require('../scrcpy');
const {
  状态,
  推送,
  安全文本,
  服务端jar路径,
} = require('../core/context');
const { 手机服务 } = require('../phone-service');

/** 已发送的帧号（单调递增） */
let 已发帧号 = 0;
/** 渲染进程回报的最后消费帧号 */
let 最后确认帧号 = 0;
/** 累计丢弃的帧数（调试面板展示） */
/**
 * 是否处于「丢弃窗口」中。
 *
 * H.264 的 P 帧依赖前一帧作为参考，随手丢掉中间的 P 帧会让解码器
 * 参考错乱、画面立刻花屏崩坏（这是上一版最严重的 bug）。
 * 正确做法：一旦判定落后，就从当前帧开始整段丢弃，直到下一个**关键帧**
 * 才开始重新发送——相当于重新建立一次解码起点。
 */

/**
 * 初始化背压回报：监听渲染进程发来的「已消费」确认。
 *
 * 说明：MessageChannelMain 在当前 Electron 版本下把 port 传给渲染进程不生效
 * （webContents.postMessage 的 transfer 不触发 window message），
 * 所以退回「主 IPC 传帧 + ipcRenderer.send 低频回报」的稳妥方案。
 * 回报每 3 帧一次，开销可忽略。
 */
function 初始化回报监听() {
  const { ipcMain } = require('electron');
  ipcMain.on('画面:回报消费', (事件, 帧号) => {
    if (typeof 帧号 === 'number' && 帧号 > 最后确认帧号) {
      最后确认帧号 = 帧号;
    }
  });
}

/** 正在等待关键帧后重发配置时暂存的 SPS/PPS */
let 待发配置 = null;

/**
 * 是否跳过当前帧。
 *
 * **结论：绝不跳帧。**
 *
 * 折腾过两版的教训：H.264 的 P/B 帧依赖前面已解码的帧作为参考，
 * 只要主进程丢掉任意一帧，解码器后面的帧就会全部参考错乱，
 * 表现为大面积色块、残影、撕裂——也就是"画面一动就崩坏"。
 * 无论"整段丢到关键帧"还是"丢 600ms 后恢复"，都救不回来，
 * 因为解码器内部状态已经和码流不匹配了。
 *
 * 卡顿要靠渲染侧解决（解码队列水位 + 只画最新帧），而不是丢输入。
 * 输入码流必须是连续的、完整的，这一条不能妥协。
 */

async function 清理通道() {
  if (状态.通道) {
    const 旧通道 = 状态.通道;
    状态.通道 = null;
    try {
      await 旧通道.关闭();
    } catch {
      // 忽略
    }
  }
}

/**
 * 连接设备。
 * @param {string} 序列号
 * @returns {Promise<object>} 设备信息
 */
async function 连接设备(序列号) {
  if (状态.连接中) throw new Error('正在连接中，请稍候');
  状态.连接中 = true;

  try {
    /*
     * 关键：连接新设备前，先彻底关闭旧通道。
     *
     * 切换设备时如果直接覆盖 状态.通道，旧通道的 socket、服务进程、
     * 事件监听器都还活着，会继续推送旧设备的视频帧，和新设备帧混在一起，
     * 导致渲染进程解码器崩坏、只能重启——这正是「切设备必崩」的根因。
     */
    await 清理通道();

    if (!状态.adb) throw new Error('adb 还没有准备好');
    if (!状态.服务) 状态.服务 = new 手机服务({ adbPath: 状态.adb.adbPath });

    const 信息 = await 状态.adb.设备信息(序列号);
    状态.设备 = 序列号;
    状态.设备信息 = 信息 || {};

    /*
     * 画质：**按手机原始分辨率推流，不再降采样**。
     *
     * 参考 scrcpy 官方 video.md 与 Escrcpy 的默认行为：
     *   > By default, scrcpy attempts to mirror at the Android device resolution.
     *   > The default video bit rate is 8 Mbps.
     * 也就是说清晰度取决于两点：**不做 max-size 限制** + **码率要与分辨率匹配**。
     *
     * 之前给短边限死 1080、码率 12Mbps，对 1280×2772 的屏幕来说
     * 等于先缩到 498×1080 再编码，细节必然糊——这就是"有点糊"的原因。
     *
     * 现在的取值：
     *   - 不设 max_size（跟随手机原生分辨率）
     *   - 码率按像素总量算：约 0.15 bit/像素/帧，再夹在 8~40 Mbps 之间
     *     1280×2772@60 → 约 31 Mbps，足够还原细节
     * 需要省性能时用户可在设置里选低清晰度。
     */
    const 设置值 = 状态.设置?.获取() || {};
    const 物理宽 = Number(状态.设备信息.width) || 1080;
    const 物理高 = Number(状态.设备信息.height) || 1920;
    const 物理短边 = Math.min(物理宽, 物理高);

    // 用手机原生分辨率推流（这一版清晰度是对的，不要再改）
    const 编码短边 = 物理短边;

    const 像素数 = 物理宽 * 物理高 * Math.pow(编码短边 / 物理短边, 2);
    // 码率：0.10 bit/px/frame，夹在 6~20 Mbps。
    // 之前给到 40Mbps 上限，USB 带宽和解码都吃紧，反而抬高延迟；
    // 20Mbps 对 1280×2772 已经足够清晰，延迟明显更低。
    const 码率 = Math.round(Math.min(20_000_000, Math.max(6_000_000, 像素数 * 0.1 * 60)));

    const 通道 = new Scrcpy通道({
      adb: 状态.adb,
      序列号,
      服务端jar: 服务端jar路径(),
      // 0 表示不限制，让服务端用原生分辨率
      最大边长: 编码短边 >= 物理短边 ? 0 : 编码短边,
      最大帧率: 60,
      码率,
    });
    通道.设置屏幕尺寸(状态.设备信息.width, 状态.设备信息.height);
    状态.通道 = 通道;

    /* ---- 视频帧 ---- */
    通道.on('配置帧', (数据) => {
      待发配置 = 数据;
    });

    通道.on('视频帧', ({ 数据, 关键帧 }) => {
      状态.帧序号 += 1;
      if (关键帧) 状态.关键帧数 += 1;

      const 片段 = 关键帧 && 待发配置 ? Buffer.concat([待发配置, 数据]) : 数据;
      if (关键帧) 待发配置 = null;

      // 不跳帧：输入码流必须完整连续，任何丢帧都会让解码器参考错乱而花屏。
      // 流畅度由渲染侧的「只画最新帧」保证。
      已发帧号 += 1;
      推送('画面:片段', { 数据: new Uint8Array(片段), 关键帧: !!关键帧, 帧号: 已发帧号 });
    });

    通道.on('会话', (会话) => 推送('画面:会话', 会话));

    /*
     * 手机分辨率变了（横竖屏切换）。
     *
     * 遇到这种情况整个通道会重建（见 scrcpy.js 里「是重复会话头」那段），
     * 新通道握手时会自带正确的宽高，所以这里**只需要通知界面刷新指标**，
     * 不要再去读 adb、也不要重连——重连由上层统一处理，避免两处同时动同一条通道。
     */
    通道.on('分辨率变化', ({ 宽, 高 }) => {
      if (!宽 || !高) return;
      推送('画面:分辨率', { 宽, 高 });
    });

    /* ---- 剪贴板：手机 → 电脑 ---- */
    通道.on('剪贴板', (文本) => {
      if (!文本) return;
      // 默认关闭：只有用户在设置里显式打开才同步
      if (状态.设置?.获取().剪贴板同步 !== true) return;
      const { clipboard } = require('electron');
      if (文本 === clipboard.readText()) return; // 是我们刚发过去的，忽略回声
      状态.手机剪贴板 = 文本;
      clipboard.writeText(文本);

      /*
       * 关键：把"最近剪贴板"也同步成这段文字。
       *
       * 定时器靠对比 最近剪贴板 来判断"电脑上是不是有了新内容"。
       * 如果这里不更新，那么手机复制过来的内容会在 500ms 后被定时器
       * 当成"用户刚在电脑上复制的东西"，再原样推回手机 ——
       * 于是手机剪贴板被自己顶掉，用户看到的就是"手机复制的东西立刻没了"。
       */
      状态.最近剪贴板 = 文本;
      推送('剪贴板:来自手机', { 文本 });
    });

    /* ---- 断开与异常 ---- */
    通道.on('关闭', (原因) => {
      推送('设备:状态', { 状态: '已断开', 原因: 安全文本(原因) });
    });
    通道.on('错误', (错误) => {
      推送('设备:状态', { 状态: '异常', 原因: 安全文本(错误 && 错误.message) });
    });
    通道.on('警告', (信息) => 推送('设备:日志', { 级别: 'warn', 信息: 安全文本(信息) }));
    通道.on('日志', (信息) => 推送('设备:日志', { 级别: 'info', 信息: 安全文本(信息) }));

    /* ---- 启动 ---- */
    const 结果 = await 通道.启动();

    // 连接完成后主动问一次手机剪贴板，保证一进来就是同步状态
    setTimeout(() => {
      if (状态.通道 === 通道) 通道.请求剪贴板(false);
    }, 800);

    // 声音输出设置：默认让电脑播放（scrcpy 会同时静音手机）
    const 声音设置 = 状态.设置?.获取() || {};
    if (声音设置.电脑发声 !== false && 状态.音频) {
      const 音频结果 = 状态.音频.开始(序列号);
      if (!音频结果.ok) 推送('设备:日志', { 级别: 'warn', 信息: 安全文本(音频结果.原因) });
    }

    推送('设备:状态', { 状态: '已连接', 序列号 });
    return { ...状态.设备信息, 会话: 结果?.会话 || 通道.会话 };
  } finally {
    状态.连接中 = false;
  }
}

/**
 * 电脑剪贴板 → 手机的实时同步。
 *
 * 用轮询比对而不是系统剪贴板事件：Electron 没有可靠的全局剪贴板变更回调，
 * 轮询 readText() 是各平台通用做法。500ms 一次，开销可忽略。
 *
 * 只在设置里打开「剪贴板同步」时才真正推送；关闭状态下定时器仍在跑但立刻返回，
 * 这样用户随时开关都能即时生效，不用重连。
 */
function 启动电脑剪贴板监听() {
  if (状态.剪贴板定时) return;

  const { clipboard } = require('electron');
  状态.最近剪贴板 = clipboard.readText();

  状态.剪贴板定时 = setInterval(() => {
    if (!状态.通道 || !状态.设备) return;
    if (状态.设置?.获取().剪贴板同步 !== true) return;

    let 当前 = '';
    try {
      当前 = clipboard.readText();
    } catch {
      return;
    }
    if (!当前 || 当前 === 状态.最近剪贴板) return;

    状态.最近剪贴板 = 当前;
    // 与手机刚同步过来的内容相同就跳过，避免两边来回回声
    if (当前 === 状态.手机剪贴板) return;

    /*
     * 第二种回声：我们自己写进剪贴板的内容。
     *
     * 「文字输入」为了让中文能粘贴到手机，会把文本写进系统剪贴板。
     * 如果不排除它，这段临时内容会被当成"用户复制了东西"再推回手机，
     * 结果就是用户真正的剪贴板被顶掉，手机那边看到的永远是占位符。
     */
    if (当前 === 状态.自写剪贴板) return;

    状态.剪贴板序号 = (状态.剪贴板序号 || 0) + 1;
    try {
      状态.通道.设置剪贴板(当前, 状态.剪贴板序号);
      推送('剪贴板:发往手机', { 文本: 当前 });
    } catch {
      // 通道正好断开，下次再试
    }
  }, 500);
}

/** 断开当前连接 */
async function 断开连接() {
  if (状态.音频) 状态.音频.停止();
  if (状态.摄像头) 状态.摄像头.关闭();
  if (状态.麦克风) 状态.麦克风.停止();

  await 清理通道();

  // 不断开 adb 设备本身：用户可能还要用 adb 调试；只清掉转发即可
  try {
    if (状态.adb && 状态.设备) await 状态.adb.移除反向转发?.(状态.设备, '');
  } catch {
    // 忽略
  }

  状态.设备 = '';
  状态.设备信息 = {};
  推送('设备:状态', { 状态: '已断开' });
}

/**
 * 只重新读取分辨率，不重建通道。
 *
 * 横竖屏切换后画面比例不对时用它：重连整条通道要杀 socket、停服务、
 * 清转发、重新推 jar、重新握手，用户会看到好几秒静止；
 * 而真正需要的只是「手机上现在的屏幕尺寸」这一个数字。
 *
 * 这里只做一次 `wm size` 的轻量读取，然后把结果交给上层去更正画布比例。
 * 通道、解码器、音频一概不动。
 */
async function 刷新分辨率() {
  if (!状态.设备) throw new Error('还没有连接设备');
  if (!状态.adb) throw new Error('adb 还没有准备好');

  const 信息 = await 状态.adb.设备信息(状态.设备);
  const 宽 = Number(信息 && 信息.width) || 0;
  const 高 = Number(信息 && 信息.height) || 0;
  if (!宽 || !高) throw new Error('读不到手机分辨率');

  // 触控坐标依赖物理分辨率，必须同步更新，否则点哪都不准
  状态.设备信息 = { ...状态.设备信息, ...信息 };
  if (状态.通道) 状态.通道.设置屏幕尺寸(宽, 高);

  return { 宽, 高 };
}

module.exports = {
  连接设备,
  断开连接,
  初始化回报监听,
  启动电脑剪贴板监听,
  清理通道,
  刷新分辨率,
  /** 调试：当前积压的帧数（= 已发 - 已确认），仅用于观测，不参与决策 */
  当前积压() {
    return 已发帧号 - 最后确认帧号;
  },
};